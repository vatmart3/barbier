// Parcours complet de réservation : node scripts/e2e-reservation.mjs http://localhost:3100 [w h]
import { chromium } from "playwright";
import { existsSync } from "node:fs";
// Chromium de l'environnement si présent, sinon celui de Playwright (npx playwright install chromium)
const chrome = () => process.env.CHROME_PATH || (existsSync("/opt/pw-browsers/chromium-1194/chrome-linux/chrome") ? "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" : undefined);
const [,, base = "http://localhost:3100", w = "1440", h = "900"] = process.argv;
const out = "/tmp/claude-0/shots";
const b = await chromium.launch({ executablePath: chrome() });
const ctx = await b.newContext({ viewport: { width: +w, height: +h }, acceptDownloads: true });
await ctx.addInitScript(() => { try { localStorage.setItem("dg-consent", JSON.stringify({ mesure: false, date: "x" })); sessionStorage.setItem("dg-seen", "1"); } catch {} });
const p = await ctx.newPage();
p.on("pageerror", (e) => console.log("PAGEERROR", e.message));
p.on("console", (m) => { if (m.type() === "error") console.log("CONSOLE", m.text().slice(0, 300)); });
await p.goto(`${base}/reserver`, { waitUntil: "networkidle" });
await p.waitForTimeout(800);
await p.getByText("Fade moyen", { exact: true }).first().click();
await p.getByText(/Taille \+10/).click();
await p.screenshot({ path: `${out}/r1-${w}.png`, fullPage: false });
await p.getByRole("button", { name: /Choisir le créneau/ }).click();
await p.waitForTimeout(700);
const slot = p.locator("fieldset button:not([disabled])").first();
console.log("premier créneau :", await slot.getAttribute("aria-label"));
await slot.click();
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/r2-${w}.png`, fullPage: false });
await p.getByRole("button", { name: /Mes coordonnées/ }).click();
await p.waitForTimeout(700);
// Soumission vide → erreurs
await p.getByRole("button", { name: /Confirmer le rendez-vous/ }).click();
await p.waitForTimeout(400);
console.log("erreurs :", await p.locator('[role="alert"]').allInnerTexts());
await p.screenshot({ path: `${out}/r3-${w}.png`, fullPage: false });
await p.fill("#prenom", "Yanis");
await p.fill("#telephone", "06 12 34 56 78");
await p.fill("#email", "yanis@exemple.fr");
await p.check('input[name="consentement"]');
await p.getByRole("button", { name: /Confirmer le rendez-vous/ }).click();
await p.waitForSelector("text=C'est noté", { timeout: 10000 });
await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/r4-${w}.png`, fullPage: false });
const [dl] = await Promise.all([p.waitForEvent("download"), p.getByRole("button", { name: /Ajouter au calendrier/ }).click()]);
const path = await dl.path();
const fs = await import("node:fs");
console.log("ICS:\n" + fs.readFileSync(path, "utf8"));
await b.close();
